//! KDE Plasma global-shortcut registration for soundboard clips (M4).
//!
//! Research-backed design (see `docs/kde-hotkeys.md`): Plasma 6 launches a
//! desktop file's `Exec` when a "command shortcut" fires, and reads the
//! default shortcut straight from the file's `X-KDE-Shortcuts` entry via
//! ksycoca. We therefore write one self-contained
//! `net.local.soundboard.<slug>.desktop` per clip into the user applications
//! directory and never touch the live-managed `~/.config/kglobalshortcutsrc`.
//!
//! The module is split into pure content builders (unit-tested here) and a
//! thin IO layer ([`write_desktop_files`]).

use std::collections::HashSet;
use std::path::Path;

use anyhow::{Context, Result};

/// Modifiers of the suggested per-clip hotkeys.
pub const KEY_PREFIX: &str = "Alt";
/// Only the first N clips (sorted) get a suggested hotkey.
pub const MAX_HOTKEY_CLIPS: usize = 9;
/// Marker proving a desktop file was generated by us (first line).
pub const GENERATOR_MARKER: &str =
    "# Managed by \"soundboard hotkeys --write\". Editing is safe; delete to remove.";

/// One clip-to-hotkey mapping with its paste-ready command.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct HotkeyEntry {
    /// Suggested key, e.g. `Alt+1`.
    pub key: String,
    /// Clip registry name.
    pub clip: String,
    /// Exact command the shortcut must run, e.g. `soundboard play "my clip"`.
    pub command: String,
}

/// Assigns `Alt+1..Alt+9` to the first [`MAX_HOTKEY_CLIPS`] clips.
/// `total_clips` is reported back so the UI can note unmapped clips.
#[must_use]
pub fn assign_keys(clips: &[&str]) -> Vec<HotkeyEntry> {
    clips
        .iter()
        .take(MAX_HOTKEY_CLIPS)
        .enumerate()
        .map(|(i, clip)| {
            let key = format!("{KEY_PREFIX}+{}", i + 1);
            let command = format!("soundboard play {}", escape_exec_arg(clip));
            HotkeyEntry {
                key,
                clip: (*clip).to_string(),
                command,
            }
        })
        .collect()
}

/// Escapes a single Exec argument per the Desktop Entry Specification:
/// the value is double-quoted; inside quotes `\`, `"`, backtick and `$` are
/// backslash-escaped, literal newlines/tabs/CRs use the `\n`/`\t`/`\r`
/// sequences. Percent signs are doubled (`%%`), as required for Exec values.
#[must_use]
pub fn escape_exec_arg(arg: &str) -> String {
    let mut out = String::with_capacity(arg.len() + 2);
    out.push('"');
    for c in arg.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '`' => out.push_str("\\`"),
            '$' => out.push_str("\\$"),
            '\n' => out.push_str("\\n"),
            '\t' => out.push_str("\\t"),
            '\r' => out.push_str("\\r"),
            '%' => out.push_str("%%"),
            other => out.push(other),
        }
    }
    out.push('"');
    out
}

/// Filesystem-safe slug for the desktop file id: ASCII lowercase
/// alphanumerics kept, everything else collapsed to `-`, empty result
/// becomes `clip`. Deterministic.
#[must_use]
fn slugify(name: &str) -> String {
    let mut out = String::with_capacity(name.len());
    for c in name.chars() {
        if c.is_ascii_alphanumeric() {
            out.push(c.to_ascii_lowercase());
        } else if !out.ends_with('-') && !out.is_empty() {
            out.push('-');
        }
    }
    while out.ends_with('-') {
        out.pop();
    }
    if out.is_empty() {
        "clip".to_string()
    } else {
        out
    }
}

/// A fully rendered desktop file for one clip.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct HotkeyFile {
    /// File name inside the user applications directory.
    pub file_name: String,
    /// Clip registry name.
    pub clip: String,
    /// Suggested key.
    pub key: String,
    /// Full desktop file content (deterministic for a given clip+key).
    pub content: String,
}

/// Builds the desktop file set for the entries: unique deterministic file
/// names (slug collisions get `-2`, `-3`, ...) and rendered content.
#[must_use]
pub fn build_files(entries: &[HotkeyEntry]) -> Vec<HotkeyFile> {
    let mut used: HashSet<String> = HashSet::new();
    entries
        .iter()
        .map(|entry| {
            let base = slugify(&entry.clip);
            let mut n = 1;
            let file_name = loop {
                let candidate = if n == 1 {
                    format!("net.local.soundboard.{base}.desktop")
                } else {
                    format!("net.local.soundboard.{base}-{n}.desktop")
                };
                if used.insert(candidate.clone()) {
                    break candidate;
                }
                n += 1;
            };
            HotkeyFile {
                file_name,
                clip: entry.clip.clone(),
                key: entry.key.clone(),
                content: render_desktop_file(&entry.clip, &entry.key),
            }
        })
        .collect()
}

/// Renders the desktop file content for one clip+key (pure, deterministic).
#[must_use]
fn render_desktop_file(clip: &str, key: &str) -> String {
    format!(
        "{GENERATOR_MARKER}\n\
         [Desktop Entry]\n\
         Type=Application\n\
         Name=Soundboard: {clip}\n\
         Exec=soundboard play {}\n\
         NoDisplay=true\n\
         StartupNotify=false\n\
         X-KDE-GlobalAccel-CommandShortcut=true\n\
         X-KDE-Shortcuts={key}\n",
        escape_exec_arg(clip)
    )
}

/// Renders the Russian clip -> key -> command table. `unmapped` is the number
/// of clips beyond [`MAX_HOTKEY_CLIPS`]; a note line is appended when > 0.
#[must_use]
pub fn render_table(entries: &[HotkeyEntry], unmapped: usize) -> String {
    let mut out = String::new();
    if entries.is_empty() {
        out.push_str("клипы не найдены — привязывать нечего\n");
        return out;
    }
    let clip_w = entries
        .iter()
        .map(|e| e.clip.chars().count())
        .max()
        .unwrap_or(0);
    let key_w = entries.iter().map(|e| e.key.len()).max().unwrap_or(0);
    out.push_str(&format!(
        "{:<clip_w$}  {:<key_w$}  {}\n",
        "Клип", "Клавиша", "Команда"
    ));
    for e in entries {
        out.push_str(&format!(
            "{:<clip_w$}  {:<key_w$}  {}\n",
            e.clip, e.key, e.command
        ));
    }
    if unmapped > 0 {
        out.push_str(&format!(
            "+ {unmapped} клипов без горячих клавиш (лимит — {MAX_HOTKEY_CLIPS})\n"
        ));
    }
    out
}

/// Renders the concise manual registration steps for Plasma 6 (Russian).
#[must_use]
pub fn render_manual_steps() -> String {
    String::from(
        "Ручная привязка (Plasma 6):\n\
         1. Параметры системы → Клавиатура → Комбинации клавиш.\n\
         2. «Добавить» → «Команда или сценарий…» — вставьте команду из таблицы.\n\
         3. Назначьте клавишу из колонки «Клавиша».\n\
         Автопривязка: soundboard hotkeys --write\n",
    )
}

/// Outcome of one [`write_desktop_files`] run (Russian strings for the CLI).
#[derive(Debug, Default, PartialEq, Eq)]
pub struct WriteOutcome {
    /// Files created.
    pub created: Vec<String>,
    /// Our files overwritten with new content (backup made).
    pub updated: Vec<String>,
    /// Files already up to date (no write happened).
    pub unchanged: Vec<String>,
    /// Backup files written before an update.
    pub backups: Vec<String>,
    /// Skipped entries with a reason.
    pub skipped: Vec<String>,
}

/// Writes the generated desktop files into `dir` (normally
/// `~/.local/share/applications`). Best-effort safety rules:
/// - an existing file WITHOUT our generator marker is never touched;
/// - our file is backed up (`<name>.bak.<timestamp>`) before an overwrite;
/// - unchanged content is not rewritten (idempotent, no backups).
#[allow(clippy::too_many_lines)] // one linear IO routine, branching per file
pub fn write_desktop_files(dir: &Path, files: &[HotkeyFile]) -> Result<WriteOutcome> {
    std::fs::create_dir_all(dir)
        .with_context(|| format!("не удалось создать каталог {}", dir.display()))?;
    let mut outcome = WriteOutcome::default();
    for file in files {
        let path = dir.join(&file.file_name);
        let existing = match std::fs::read_to_string(&path) {
            Ok(text) => Some(text),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => None,
            Err(e) => {
                outcome
                    .skipped
                    .push(format!("{}: не удалось прочитать: {e}", file.file_name));
                continue;
            }
        };
        match existing {
            Some(text) if text == file.content => {
                outcome.unchanged.push(file.file_name.clone());
            }
            Some(text) if !text.starts_with(GENERATOR_MARKER) => {
                outcome.skipped.push(format!(
                    "{}: файл существует и создан не soundboard — не трогаю",
                    file.file_name
                ));
            }
            Some(text) => {
                let stamp = backup_stamp();
                let backup = dir.join(format!("{}.bak.{stamp}", file.file_name));
                std::fs::write(&backup, text)
                    .with_context(|| format!("не удалось записать {}", backup.display()))?;
                outcome.backups.push(backup.file_name().map_or_else(
                    || backup.display().to_string(),
                    |n| n.to_string_lossy().to_string(),
                ));
                match std::fs::write(&path, &file.content) {
                    Ok(()) => outcome.updated.push(file.file_name.clone()),
                    Err(e) => outcome
                        .skipped
                        .push(format!("{}: не удалось записать: {e}", file.file_name)),
                }
            }
            None => match std::fs::write(&path, &file.content) {
                Ok(()) => outcome.created.push(file.file_name.clone()),
                Err(e) => outcome
                    .skipped
                    .push(format!("{}: не удалось записать: {e}", file.file_name)),
            },
        }
    }
    Ok(outcome)
}

/// Timestamp suffix for backups: seconds + millis since the epoch.
fn backup_stamp() -> u128 {
    match std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH) {
        Ok(d) => d.as_secs() as u128 * 1000 + u128::from(d.subsec_millis()),
        Err(_) => 0,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn assign_keys_first_nine_sorted() {
        let owned: Vec<String> = (0..12).map(|i| format!("clip{i:02}")).collect();
        let clips: Vec<&str> = owned.iter().map(String::as_str).collect();
        let entries = assign_keys(&clips);
        assert_eq!(entries.len(), 9);
        assert_eq!(entries[0].key, "Alt+1");
        assert_eq!(entries[8].key, "Alt+9");
        assert_eq!(entries[0].clip, "clip00");
        assert_eq!(entries[0].command, "soundboard play \"clip00\"");
    }

    #[test]
    fn assign_keys_two_clips_two_keys() {
        let entries = assign_keys(&["b.wav", "a"]);
        assert_eq!(entries.len(), 2);
        assert_eq!(entries[0].key, "Alt+1");
        assert_eq!(entries[1].key, "Alt+2");
    }

    #[test]
    fn assign_keys_empty_is_empty() {
        assert!(assign_keys(&[]).is_empty());
    }

    #[test]
    fn escape_plain_name_is_quoted() {
        assert_eq!(escape_exec_arg("airhorn"), "\"airhorn\"");
    }

    #[test]
    fn escape_space_is_quoted_only() {
        assert_eq!(escape_exec_arg("air horn"), "\"air horn\"");
    }

    #[test]
    fn escape_quote_backslash_dollar_backtick() {
        assert_eq!(escape_exec_arg("say \"hi\""), "\"say \\\"hi\\\"\"");
        assert_eq!(escape_exec_arg("back\\slash"), "\"back\\\\slash\"");
        assert_eq!(escape_exec_arg("$HOME `rm`"), "\"\\$HOME \\`rm\\`\"");
    }

    #[test]
    fn escape_percent_is_doubled() {
        assert_eq!(escape_exec_arg("100%"), "\"100%%\"");
    }

    #[test]
    fn escape_unicode_passes_through() {
        assert_eq!(escape_exec_arg("кот-обормот"), "\"кот-обормот\"");
    }

    #[test]
    fn escape_whitespace_control_sequences() {
        assert_eq!(escape_exec_arg("a\nb\tc\rd"), "\"a\\nb\\tc\\rd\"");
    }

    #[test]
    fn slugify_rules() {
        assert_eq!(slugify("air horn!"), "air-horn");
        assert_eq!(slugify("AirHorn_2"), "airhorn-2");
        assert_eq!(slugify("кот-обормот"), "clip");
        assert_eq!(slugify("---"), "clip");
    }

    #[test]
    fn file_names_are_unique_on_slug_collision() {
        let entries = assign_keys(&["kot", "kot 2", "Kot"]);
        let files = build_files(&entries);
        let mut names: Vec<&str> = files.iter().map(|f| f.file_name.as_str()).collect();
        names.sort();
        assert_eq!(
            names,
            vec![
                "net.local.soundboard.kot-2.desktop",
                "net.local.soundboard.kot-3.desktop",
                "net.local.soundboard.kot.desktop",
            ]
        );
    }

    #[test]
    fn desktop_file_content_is_deterministic_and_complete() {
        let a = render_desktop_file("my clip", "Alt+1");
        let b = render_desktop_file("my clip", "Alt+1");
        assert_eq!(a, b);
        assert!(a.starts_with(GENERATOR_MARKER));
        assert!(a.contains("[Desktop Entry]\n"));
        assert!(a.contains("Name=Soundboard: my clip\n"));
        assert!(a.contains("Exec=soundboard play \"my clip\"\n"));
        assert!(a.contains("X-KDE-Shortcuts=Alt+1\n"));
        assert!(a.contains("X-KDE-GlobalAccel-CommandShortcut=true\n"));
        assert!(a.contains("NoDisplay=true\n"));
    }

    #[test]
    fn table_zero_clips() {
        assert_eq!(
            render_table(&[], 0),
            "клипы не найдены — привязывать нечего\n"
        );
    }

    #[test]
    fn table_two_clips_aligned() {
        let entries = assign_keys(&["a", "b"]);
        let table = render_table(&entries, 0);
        assert!(table.contains("Клип"));
        assert!(table.contains("a  Alt+1  soundboard play \"a\""));
        assert!(table.contains("b  Alt+2  soundboard play \"b\""));
        assert!(!table.contains("без горячих клавиш"));
    }

    #[test]
    fn table_twelve_clips_notes_unmapped() {
        let owned: Vec<String> = (0..12).map(|i| format!("c{i:02}")).collect();
        let clips: Vec<&str> = owned.iter().map(String::as_str).collect();
        let entries = assign_keys(&clips);
        let table = render_table(&entries, 3);
        assert_eq!(table.lines().count(), 1 + 9 + 1); // header + 9 rows + note
        assert!(table.contains("+ 3 клипов без горячих клавиш"));
    }

    #[test]
    fn table_rendering_is_deterministic() {
        let entries = assign_keys(&["x y", "z"]);
        assert_eq!(render_table(&entries, 1), render_table(&entries, 1));
    }

    #[test]
    fn write_creates_then_is_idempotent() {
        let dir = tempfile::tempdir().expect("tempdir");
        let entries = assign_keys(&["my clip"]);
        let files = build_files(&entries);

        let first = write_desktop_files(dir.path(), &files).expect("write 1");
        assert_eq!(first.created, vec!["net.local.soundboard.my-clip.desktop"]);
        assert!(first.skipped.is_empty());

        let second = write_desktop_files(dir.path(), &files).expect("write 2");
        assert!(second.created.is_empty());
        assert_eq!(
            second.unchanged,
            vec!["net.local.soundboard.my-clip.desktop"]
        );
        assert!(second.backups.is_empty());
    }

    #[test]
    fn write_updates_with_backup_when_key_changes() {
        let dir = tempfile::tempdir().expect("tempdir");
        let old = build_files(&assign_keys(&["clip"]));
        write_desktop_files(dir.path(), &old).expect("write old");

        let new = build_files(&assign_keys(&["clip"]));
        // Simulate a changed binding by rewriting content via a new key.
        let changed = new
            .iter()
            .map(|f| HotkeyFile {
                key: "Alt+5".to_string(),
                content: render_desktop_file(&f.clip, "Alt+5"),
                ..f.clone()
            })
            .collect::<Vec<_>>();
        let outcome = write_desktop_files(dir.path(), &changed).expect("write new");
        assert_eq!(outcome.updated, vec!["net.local.soundboard.clip.desktop"]);
        assert_eq!(outcome.backups.len(), 1);
        let backup = dir.path().join(&outcome.backups[0]);
        let backup_text = std::fs::read_to_string(backup).expect("backup readable");
        assert!(backup_text.contains("X-KDE-Shortcuts=Alt+1\n"));
        let on_disk = std::fs::read_to_string(dir.path().join("net.local.soundboard.clip.desktop"))
            .expect("file readable");
        assert!(on_disk.contains("X-KDE-Shortcuts=Alt+5\n"));
    }

    #[test]
    fn write_never_touches_foreign_file() {
        let dir = tempfile::tempdir().expect("tempdir");
        let foreign = dir.path().join("net.local.soundboard.clip.desktop");
        std::fs::write(&foreign, "[Desktop Entry]\nType=Application\nName=mine\n").expect("seed");
        let files = build_files(&assign_keys(&["clip"]));
        let outcome = write_desktop_files(dir.path(), &files).expect("write");
        assert!(outcome.created.is_empty());
        assert_eq!(outcome.skipped.len(), 1);
        assert!(outcome.skipped[0].contains("создан не soundboard"));
        let after = std::fs::read_to_string(&foreign).expect("read foreign");
        assert!(after.contains("Name=mine\n"));
    }

    #[test]
    fn manual_steps_mention_settings_path_and_write_flag() {
        let steps = render_manual_steps();
        assert!(steps.contains("Параметры системы"));
        assert!(steps.contains("Команда или сценарий"));
        assert!(steps.contains("soundboard hotkeys --write"));
    }
}
